# Aqui a gente vai guardar livros dentro de uma "estante".
# Cada livro tem um título e um autor.
# A estante guarda uma LISTA de livros.

# ---------------------------------------------------------
# 1) Primeiro, criamos a "receita" (classe) de um LIVRO
# ---------------------------------------------------------
class Livro:

    # Isso aqui roda toda vez que a gente CRIA um livro novo.
    # Exemplo: Livro("Dom Casmurro", "Machado de Assis")
    def __init__(self, titulo, autor):
        self.titulo = titulo   # guarda o título dentro do livro
        self.autor = autor     # guarda o autor dentro do livro

    # Essa função só serve pra MOSTRAR o livro na tela
    def apresentar(self):
        print("- " + self.titulo + " (" + self.autor + ")")


# ---------------------------------------------------------
# 2) Agora criamos a "receita" (classe) da ESTANTE
# ---------------------------------------------------------
class Estante:

    # Toda estante tem um nome e começa SEM nenhum livro
    def __init__(self, nome):
        self.nome = nome
        self.livros = []   # lista vazia, ainda sem livros

    # Função para ADICIONAR um livro na estante
    def cadastrar_livro(self, livro_novo):

        # Antes de adicionar, vamos checar se JÁ EXISTE
        # um livro com esse mesmo título na estante.
        # Pra isso, olhamos livro por livro que já está guardado.
        for livro_que_ja_existe in self.livros:

            # Se o título for igual (ignorando maiúscula/minúscula)...
            if livro_que_ja_existe.titulo.lower() == livro_novo.titulo.lower():
                print("Opa! Já existe um livro com o título '" + livro_novo.titulo + "'. Cadastro recusado.")
                return   # para a função aqui, não deixa cadastrar

        # Se chegou até aqui, é porque não achou repetido.
        # Então pode adicionar o livro na lista.
        self.livros.append(livro_novo)
        print("Livro '" + livro_novo.titulo + "' cadastrado com sucesso!")

    # Função para MOSTRAR todos os livros da estante
    def listar_livros(self):
        print("")
        print("--- Livros da estante " + self.nome + " ---")

        # Se a lista estiver vazia, avisamos
        if len(self.livros) == 0:
            print("Não há livros cadastrados.")
        else:
            # Se tiver livro, mostramos um por um
            for livro in self.livros:
                livro.apresentar()

        print("----------------------------------")


# ---------------------------------------------------------
# 3) Agora vamos criar a NOSSA estante e fazer o menu rodar
# ---------------------------------------------------------

# Cria a estante chamada "Minha Estante"
estante = Estante("Minha Estante")

# Esse "while True" faz o programa ficar rodando pra sempre,
# até a gente escolher a opção de SAIR
while True:

    # Mostra o menu de opções
    print("")
    print("===== MENU =====")
    print("1 - Cadastrar livro")
    print("2 - Listar livros")
    print("3 - Sair")

    # Pergunta pro usuário o que ele quer fazer
    opcao_digitada = input("Escolha uma opção: ")

    # AQUI está o "escudo de proteção" contra erro.
    # Se o usuário digitar uma letra em vez de número,
    # o programa NÃO vai quebrar, porque a gente testa antes.
    if opcao_digitada.isdigit():
        opcao = int(opcao_digitada)   # transforma o texto em número
    else:
        print("Isso não é um número! Digite 1, 2 ou 3.")
        continue   # volta pro início do while, sem fazer mais nada

    # Agora sim, verificamos qual opção o usuário escolheu

    if opcao == 1:
        # Pergunta o título e o autor do livro novo
        titulo_digitado = input("Digite o título do livro: ")
        autor_digitado = input("Digite o autor do livro: ")

        # Cria um livro novo com esses dados
        livro_novo = Livro(titulo_digitado, autor_digitado)

        # Manda a estante tentar cadastrar esse livro
        estante.cadastrar_livro(livro_novo)

    elif opcao == 2:
        # Manda a estante mostrar todos os livros que ela tem
        estante.listar_livros()

    elif opcao == 3:
        print("Saindo do sistema. Até mais!")
        break   # esse "break" é o que FAZ o while parar

    else:
        # Se digitou um número que não é 1, 2 ou 3
        print("Opção inválida! Escolha 1, 2 ou 3.")